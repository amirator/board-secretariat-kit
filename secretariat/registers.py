"""Resolutions register and action log: load, update from a meeting, flag overdue items, write CSV and Excel."""
from __future__ import annotations

import csv
import datetime as dt
from pathlib import Path

from openpyxl import Workbook
from openpyxl.formatting.rule import FormulaRule
from openpyxl.styles import Alignment, Border, Font, PatternFill, Side
from openpyxl.utils import get_column_letter
from openpyxl.workbook.defined_name import DefinedName
from openpyxl.worksheet.datavalidation import DataValidation

from .model import ACTION_STATUSES, IMPL_STATUSES, Company, InputError, Meeting

RES_COLUMNS = ["ref", "body", "meeting_id", "meeting_date", "item", "title", "resolution_text", "type",
               "votes_for", "votes_against", "votes_abstain", "outcome", "owner", "implementation_status", "notes"]
ACT_COLUMNS = ["id", "body", "meeting_id", "meeting_date", "item", "action", "owner", "due_date", "status",
               "closed_date", "update_note"]
SAMPLE_LINE = "# SAMPLE / DEMO DATA. Fictional records generated by board-secretariat-kit. Not real company records."

NAVY, GREY = "1F2A44", "F2F4F7"
RAG = {"Overdue": "F8D7DA", "Due soon": "FFF3CD", "On track": "E2EFDA", "Closed": "E7E9EE", "Deferred": "E7E9EE"}


def _read_csv(path: Path, columns: list[str]) -> list[dict]:
    with open(path, encoding="utf-8", newline="") as fh:
        rows = list(csv.DictReader(line for line in fh if not line.startswith("#")))
    if rows and set(columns) - set(rows[0]):
        raise InputError([f"missing column(s): {sorted(set(columns) - set(rows[0]))}"], str(path))
    return rows


def load_registers(folder: Path | str) -> tuple[list[dict], list[dict]]:
    folder = Path(folder)
    res = _read_csv(folder / "resolutions_register.csv", RES_COLUMNS)
    act = _read_csv(folder / "action_log.csv", ACT_COLUMNS)
    problems = []
    for r in act:
        try:
            r["due_date"] = dt.date.fromisoformat(r["due_date"])
        except ValueError:
            problems.append(f"action {r.get('id')}: due_date {r.get('due_date')!r} is not YYYY-MM-DD")
        r["closed_date"] = dt.date.fromisoformat(r["closed_date"]) if r.get("closed_date") else None
        r["meeting_date"] = dt.date.fromisoformat(r["meeting_date"])
        if r["status"] not in ACTION_STATUSES:
            problems.append(f"action {r['id']}: status {r['status']!r} not in {ACTION_STATUSES}")
    for r in res:
        r["meeting_date"] = dt.date.fromisoformat(r["meeting_date"])
        for k in ("votes_for", "votes_against", "votes_abstain"):
            r[k] = int(r[k] or 0)
        if r["implementation_status"] not in IMPL_STATUSES:
            problems.append(f"resolution {r['ref']}: implementation_status {r['implementation_status']!r} not in {IMPL_STATUSES}")
    for name, rows, key in (("resolution", res, "ref"), ("action", act, "id")):
        keys = [r[key] for r in rows]
        dupes = sorted({k for k in keys if keys.count(k) > 1})
        if dupes:
            problems.append(f"duplicate {name} numbers: {dupes}")
    if problems:
        raise InputError(problems, str(folder))
    return res, act


def apply_meeting(meeting: Meeting, resolutions: list[dict], actions: list[dict]) -> tuple[list[dict], list[dict], list[dict]]:
    """Return updated copies of both registers plus the list of action updates that were applied."""
    res = [dict(r) for r in resolutions]
    act = [dict(a) for a in actions]
    if not meeting.record:
        return res, act, []
    if any(r["meeting_id"] == meeting.id for r in res) or any(a["meeting_id"] == meeting.id for a in act):
        raise InputError([f"the registers already contain entries for {meeting.id}; it has been applied before"], meeting.id)
    for r in meeting.resolutions:
        t = r["tally"]
        res.append({
            "ref": r["ref"], "body": meeting.body.code, "meeting_id": meeting.id, "meeting_date": meeting.date,
            "item": r["item"], "title": r["title"], "resolution_text": r["text"], "type": r["type"],
            "votes_for": t["for"], "votes_against": t["against"], "votes_abstain": t["abstain"],
            "outcome": t["outcome"], "owner": r.get("owner", ""),
            "implementation_status": "Not started" if t["carried"] else "Not applicable", "notes": "",
        })
    by_id = {a["id"]: a for a in act}
    applied = []
    problems = []
    for u in meeting.record.get("action_updates") or []:
        a = by_id.get(u["id"])
        if a is None:
            problems.append(f"action update {u['id']}: no such action in the log")
            continue
        before = a["status"]
        a["status"] = u["status"]
        if u.get("due"):
            a["due_date"] = u["due"]
        if u["status"] == "Closed":
            a["closed_date"] = u.get("closed_date") or meeting.date
        a["update_note"] = u.get("note", "")
        applied.append({**a, "previous_status": before})
    if problems:
        raise InputError(problems, meeting.id)
    for a in meeting.actions:
        act.append({
            "id": a["id"], "body": meeting.body.code, "meeting_id": meeting.id, "meeting_date": meeting.date,
            "item": a["item"], "action": a["action"], "owner": a["owner"], "due_date": a["due"],
            "status": "Open", "closed_date": None, "update_note": "",
        })
    return res, act, applied


# ------------------------------------------------------------------ flags (mirrors the Excel formulas)

def action_flag(status: str, due: dt.date, as_of: dt.date, soon_days: int = 7) -> str:
    if status == "Closed":
        return "Closed"
    if status == "Deferred":
        return "Deferred"
    if due < as_of:
        return "Overdue"
    if due <= as_of + dt.timedelta(days=soon_days):
        return "Due soon"
    return "On track"


def days_overdue(status: str, due: dt.date, as_of: dt.date) -> int:
    if status in ("Closed", "Deferred"):
        return 0
    return max(0, (as_of - due).days)


def summarise(actions: list[dict], resolutions: list[dict], as_of: dt.date, soon_days: int = 7) -> dict:
    flags = [action_flag(a["status"], a["due_date"], as_of, soon_days) for a in actions]
    open_flags = [f for f in flags if f in ("Overdue", "Due soon", "On track")]
    overdue = [(a, days_overdue(a["status"], a["due_date"], as_of)) for a, f in zip(actions, flags) if f == "Overdue"]
    return {
        "as_of": as_of, "actions_total": len(actions), "open": len(open_flags),
        "overdue": len(overdue), "due_soon": flags.count("Due soon"), "on_track": flags.count("On track"),
        "closed": flags.count("Closed"), "deferred": flags.count("Deferred"),
        "oldest_overdue": max(overdue, key=lambda x: x[1]) if overdue else None,
        "resolutions_total": len(resolutions),
        "awaiting_implementation": sum(r["implementation_status"] in ("Not started", "In progress") for r in resolutions),
    }


# ------------------------------------------------------------------ writers

def _fmt(v):
    if isinstance(v, dt.date):
        return v.isoformat()
    return "" if v is None else v


def write_csvs(folder: Path | str, resolutions: list[dict], actions: list[dict]) -> None:
    folder = Path(folder)
    folder.mkdir(parents=True, exist_ok=True)
    for name, rows, cols in (("resolutions_register.csv", resolutions, RES_COLUMNS), ("action_log.csv", actions, ACT_COLUMNS)):
        with open(folder / name, "w", encoding="utf-8", newline="") as fh:
            fh.write(SAMPLE_LINE + "\n")
            w = csv.DictWriter(fh, fieldnames=cols)
            w.writeheader()
            for r in rows:
                w.writerow({c: _fmt(r.get(c)) for c in cols})


def _header(ws, row: int, headers: list[str], widths: list[int]):
    thin = Side(style="thin", color="C9CED6")
    for i, (h, w) in enumerate(zip(headers, widths), start=1):
        c = ws.cell(row=row, column=i, value=h)
        c.font = Font(bold=True, color="FFFFFF")
        c.fill = PatternFill("solid", fgColor=NAVY)
        c.alignment = Alignment(vertical="center", wrap_text=True)
        c.border = Border(bottom=thin)
        ws.column_dimensions[get_column_letter(i)].width = w
    ws.row_dimensions[row].height = 30


def _banner(ws, text: str, ncols: int):
    ws.cell(row=1, column=1, value=text).font = Font(bold=True, size=14, color=NAVY)
    b = ws.cell(row=2, column=1, value="SAMPLE / DEMO DATA: fictional company and people. Not real company records.")
    b.font = Font(bold=True, color="9C0006")
    b.fill = PatternFill("solid", fgColor="FFC7CE")
    ws.merge_cells(start_row=2, start_column=1, end_row=2, end_column=ncols)


def _print_setup(ws, header_row: int):
    ws.page_setup.orientation = "landscape"
    ws.page_setup.paperSize = ws.PAPERSIZE_A4
    ws.page_setup.fitToWidth = 1
    ws.page_setup.fitToHeight = 0
    ws.sheet_properties.pageSetUpPr.fitToPage = True
    ws.print_title_rows = f"{header_row}:{header_row}"
    ws.oddFooter.center.text = "Page &P of &N"


def write_workbook(path: Path | str, company: Company, resolutions: list[dict], actions: list[dict],
                   as_of: dt.date, title: str) -> dict:
    """Excel register with live formulas: change AsOf or a status and the flags and counts update."""
    soon = company.due_soon_days
    name = lambda pid: company.people[pid].name if pid in company.people else pid  # noqa: E731
    wb = Workbook()
    ws = wb.active
    ws.title = "Summary"
    al = wb.create_sheet("Action log")
    rr = wb.create_sheet("Resolutions")

    # --- Action log
    H = 4
    _banner(al, f"{company.name}: action log", 13)
    heads = ["Action ID", "Body", "Meeting", "Meeting date", "Item", "Action", "Owner", "Due date", "Status",
             "Closed date", "Latest update", "Days overdue", "Flag"]
    _header(al, H, heads, [12, 7, 13, 12, 6, 52, 20, 12, 12, 12, 34, 9, 11])
    first = H + 1
    acts = sorted(actions, key=lambda a: a["id"])
    for i, a in enumerate(acts, start=first):
        vals = [a["id"], a["body"], a["meeting_id"], a["meeting_date"], int(a["item"]), a["action"], name(a["owner"]),
                a["due_date"], a["status"], a["closed_date"], a.get("update_note") or ""]
        for j, v in enumerate(vals, start=1):
            c = al.cell(row=i, column=j, value=v)
            c.alignment = Alignment(vertical="top", wrap_text=j in (6, 11), horizontal="center" if j == 5 else None)
            if isinstance(v, dt.date):
                c.number_format = "dd mmm yyyy"
        d = al.cell(row=i, column=12, value=f'=IF(OR(I{i}="Closed",I{i}="Deferred"),0,MAX(0,AsOf-H{i}))')
        d.number_format = '0;-0;"";@'  # hide zeros
        f = al.cell(row=i, column=13, value=(f'=IF(I{i}="Closed","Closed",IF(I{i}="Deferred","Deferred",'
                                             f'IF(H{i}<AsOf,"Overdue",IF(H{i}<=AsOf+SoonDays,"Due soon","On track"))))'))
        d.alignment = f.alignment = Alignment(vertical="top", horizontal="center")
    last = first + len(acts) - 1
    dv = DataValidation(type="list", formula1='"' + ",".join(ACTION_STATUSES) + '"', allow_blank=False)
    dv.error, dv.errorTitle = "Pick a status from the list", "Status"
    al.add_data_validation(dv)
    dv.add(f"I{first}:I{max(last, first) + 200}")
    for flag, color in RAG.items():
        al.conditional_formatting.add(f"A{first}:M{max(last, first)}", FormulaRule(
            formula=[f'$M{first}="{flag}"'], fill=PatternFill("solid", fgColor=color)))
    al.freeze_panes = f"B{first}"
    al.auto_filter.ref = f"A{H}:M{max(last, first)}"
    _print_setup(al, H)

    # --- Resolutions register
    _banner(rr, f"{company.name}: resolutions register", 13)
    rheads = ["Ref", "Body", "Meeting", "Date", "Item", "Title", "Resolved that", "Type", "For", "Against",
              "Abstain", "Outcome", "Owner", "Implementation"]
    _header(rr, H, rheads, [14, 7, 13, 12, 6, 34, 52, 9, 6, 8, 8, 11, 18, 15])
    ress = sorted(resolutions, key=lambda r: (r["meeting_date"], r["ref"]))
    for i, r in enumerate(ress, start=first):
        vals = [r["ref"], r["body"], r["meeting_id"], r["meeting_date"], int(r["item"]), r["title"], r["resolution_text"],
                r["type"], r["votes_for"], r["votes_against"], r["votes_abstain"], r["outcome"], name(r["owner"]),
                r["implementation_status"]]
        for j, v in enumerate(vals, start=1):
            c = rr.cell(row=i, column=j, value=v)
            c.alignment = Alignment(vertical="top", wrap_text=j in (6, 7), horizontal="center" if j in (5, 9, 10, 11) else None)
            if isinstance(v, dt.date):
                c.number_format = "dd mmm yyyy"
    rlast = first + len(ress) - 1
    dv2 = DataValidation(type="list", formula1='"' + ",".join(IMPL_STATUSES) + '"', allow_blank=False)
    rr.add_data_validation(dv2)
    dv2.add(f"N{first}:N{max(rlast, first) + 200}")
    for status, color in (("Not started", "FFF3CD"), ("In progress", "FFF3CD"), ("Implemented", "E2EFDA")):
        rr.conditional_formatting.add(f"N{first}:N{max(rlast, first)}", FormulaRule(
            formula=[f'$N{first}="{status}"'], fill=PatternFill("solid", fgColor=color)))
    rr.freeze_panes = f"B{first}"
    rr.auto_filter.ref = f"A{H}:N{max(rlast, first)}"
    _print_setup(rr, H)

    # --- Summary
    _banner(ws, title, 6)
    ws["A4"], ws["B4"] = "As at (edit to re-flag)", as_of
    ws["B4"].number_format = "dd mmm yyyy"
    ws["A5"], ws["B5"] = "'Due soon' window (days)", soon
    for c in ("B4", "B5"):
        ws[c].fill = PatternFill("solid", fgColor="FFF3CD")
        ws[c].font = Font(bold=True)
    wb.defined_names["AsOf"] = DefinedName("AsOf", attr_text="Summary!$B$4")
    wb.defined_names["SoonDays"] = DefinedName("SoonDays", attr_text="Summary!$B$5")
    flag_rng = f"'Action log'!$M${first}:$M${max(last, first)}"
    own_rng = f"'Action log'!$G${first}:$G${max(last, first)}"
    ws["A7"] = "Actions"
    ws["A7"].font = Font(bold=True, color=NAVY, size=12)
    rows = [("Open (all)", f'=COUNTIF({flag_rng},"Overdue")+COUNTIF({flag_rng},"Due soon")+COUNTIF({flag_rng},"On track")'),
            ("Overdue", f'=COUNTIF({flag_rng},"Overdue")'), ("Due soon", f'=COUNTIF({flag_rng},"Due soon")'),
            ("On track", f'=COUNTIF({flag_rng},"On track")'), ("Closed", f'=COUNTIF({flag_rng},"Closed")'),
            ("Deferred", f'=COUNTIF({flag_rng},"Deferred")')]
    for i, (k, f) in enumerate(rows, start=8):
        ws.cell(row=i, column=1, value=k)
        ws.cell(row=i, column=2, value=f)
        if k in RAG:
            ws.cell(row=i, column=1).fill = PatternFill("solid", fgColor=RAG[k])

    ws["D7"] = "Open actions by owner"
    ws["D7"].font = Font(bold=True, color=NAVY, size=12)
    for j, h in enumerate(["Owner", "Open", "Overdue"], start=4):
        c = ws.cell(row=8, column=j, value=h)
        c.font, c.fill = Font(bold=True, color="FFFFFF"), PatternFill("solid", fgColor=NAVY)
    owners = sorted({name(a["owner"]) for a in actions if a["status"] not in ("Closed", "Deferred")})
    for i, o in enumerate(owners, start=9):
        ws.cell(row=i, column=4, value=o)
        ws.cell(row=i, column=5, value=(f'=COUNTIFS({own_rng},D{i},{flag_rng},"Overdue")+COUNTIFS({own_rng},D{i},{flag_rng},"Due soon")'
                                        f'+COUNTIFS({own_rng},D{i},{flag_rng},"On track")'))
        ws.cell(row=i, column=6, value=f'=COUNTIFS({own_rng},D{i},{flag_rng},"Overdue")')

    r0 = 16
    ws.cell(row=r0, column=1, value="Resolutions by implementation status").font = Font(bold=True, color=NAVY, size=12)
    impl_rng = f"Resolutions!$N${first}:$N${max(rlast, first)}"
    for i, s in enumerate(IMPL_STATUSES, start=r0 + 1):
        ws.cell(row=i, column=1, value=s)
        ws.cell(row=i, column=2, value=f'=COUNTIF({impl_rng},A{i})')

    s = summarise(actions, resolutions, as_of, soon)
    note = (f"As at {as_of:%d %b %Y}: {s['open']} open actions, {s['overdue']} overdue, {s['due_soon']} due within {soon} days; "
            f"{s['awaiting_implementation']} resolutions awaiting implementation.")
    if s["oldest_overdue"]:
        a, d = s["oldest_overdue"]
        note += f" Oldest overdue: {a['id']} ({name(a['owner'])}), {d} days."
    ws.cell(row=r0 + 6, column=1, value="Note written by the generator from the same rules as the formulas above:").font = Font(italic=True)
    ws.cell(row=r0 + 7, column=1, value=note).alignment = Alignment(wrap_text=True, vertical="top")
    ws.merge_cells(start_row=r0 + 7, start_column=1, end_row=r0 + 7, end_column=6)
    ws.row_dimensions[r0 + 7].height = 48
    for col, w in zip("ABCDEF", (34, 12, 4, 26, 8, 9)):
        ws.column_dimensions[col].width = w
    _print_setup(ws, 1)
    ws.page_setup.orientation = "portrait"

    path = Path(path)
    path.parent.mkdir(parents=True, exist_ok=True)
    wb.save(path)
    return s
